#!/usr/bin/env python3
"""Build Fahhh.ZDL from fahhh.c + fahhh_sample.h + manifest_pedal.json.

Run from repo root: python3 build_all.py fahhh

fahhh_sample.h is generated by make_sample.py from the source recording and is
checked in, so this build does not need the recording. The sample is most of
the file: the size guard (build/zdl_size_guard.py) runs on the result.
"""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent.parent           # src/custom/fahhh/build.py -> repo root
sys.path.insert(0, str(ROOT / "build"))
sys.path.insert(0, str(ROOT / "src" / "airwindows" / "common"))

from linker import LinkerConfig, link, params_from_manifest  # noqa: E402
from manifest_params import write_param_header  # noqa: E402
from custom_covers import make_cover  # noqa: E402
from zdl_size_guard import check as check_size  # noqa: E402

# The macOS install path by default; TI_ROOT overrides it (e.g. a Linux/WSL
# install at ~/ti/ti-cgt-c6000_8.5.0.LTS).
TI_ROOT = Path(os.environ.get("TI_ROOT", "/Applications/ti/ti-cgt-c6000_8.5.0.LTS"))
CL6X = TI_ROOT / "bin" / "cl6x"

CFLAGS = [
    "--c99",
    "--opt_level=2",
    "-mv6740",
    "--abi=eabi",
    "--mem_model:data=far",
    f"--include_path={TI_ROOT}/include",
]


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--audio-nop", action="store_true",
                    help="smoke build: the audio function returns at once (dry passes), "
                         "everything else (UI, descriptor, cover, init) is the full build's. "
                         "Same name, group and ID, so it tests the identity the release will use.")
    ap.add_argument("--out-dir", type=Path, default=None,
                    help="where to write Fahhh.ZDL (default dist/, or build/probes/fahhh-nop/ with --audio-nop)")
    args = ap.parse_args()

    manifest = json.loads((HERE / "manifest_pedal.json").read_text())
    if args.audio_nop:
        manifest["audio_nop"] = True
    write_param_header(manifest, HERE / "fahhh_params.h", "FAHHH")
    if not (HERE / "fahhh_sample.h").exists():
        raise SystemExit("fahhh_sample.h is missing: run make_sample.py on the recording first")

    src_c = HERE / "fahhh.c"
    if args.out_dir is not None:
        out_dir = args.out_dir.resolve()
    elif manifest.get("audio_nop"):
        out_dir = ROOT / "build" / "probes" / "fahhh-nop"   # never next to the real build in dist/
    else:
        out_dir = ROOT / "dist"
    out_dir.mkdir(parents=True, exist_ok=True)

    effect_name = manifest["effect_name"]
    audio_func = manifest["audio_func_name"]
    obj = HERE / f"{effect_name.lower()}.obj"
    out_zdl = out_dir / f"{effect_name}.ZDL"

    print(f"[fahhh] compiling {src_c.name} -> {obj.name}")
    subprocess.run(
        [
            str(CL6X),
            *CFLAGS,
            f"--define=FAHHH_AUDIO_FUNC={audio_func}",
            "-c",
            str(src_c),
            f"--output_file={obj}",
        ],
        check=True,
        cwd=HERE,
    )

    for junk in ("compiler.opt", "linker.cmd"):
        p = HERE / junk
        if p.exists():
            p.unlink()

    cfg = LinkerConfig(
        materialize_init=True,
        effect_name=effect_name,
        screen_image=make_cover(effect_name, [p["name"] for p in manifest["params"]]),
        audio_func_name=audio_func,
        gid=manifest["gid"],
        fxid=manifest["fxid"],
        params=params_from_manifest(manifest["params"]),
        obj_path=obj,
        output_path=out_zdl,
        fxid_version=manifest.get("fxid_version", "1.00").encode("ascii"),
        flags_byte=manifest.get("flags_byte", 0x01),
        audio_nop=manifest.get("audio_nop", False),
        knob_positions=[(2, 14, 46), (3, 55, 46), (4, 96, 46)],
        use_object_edit_handlers=False,
        synthesize_linesel_edit_handlers=True,
        synth_edit_start_index=2,
        knob3_blob_path="/tmp/__nonexistent__",
        dsp_cost=float(manifest["dsp_cost"]),
    )
    link(cfg)
    check_size(out_zdl)

    print(f"\n[fahhh] done -> {out_zdl}")


if __name__ == "__main__":
    main()
