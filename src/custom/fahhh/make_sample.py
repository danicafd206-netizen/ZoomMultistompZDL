#!/usr/bin/env python3
"""Turn the "Fahhh" recording into fahhh_sample.h (4-bit IMA ADPCM).

A ZDL must stay at or under 32,126 bytes (build/zdl_size_guard.py), so the
sample cannot ride in as PCM: 2.2 s of 16-bit 44.1 kHz audio is 194 KB. It is
stored here as mono IMA ADPCM, 4 bits a sample, and the pedal decodes it
once into its ctx[3] arena (fahhh.c). The defaults are the owner's choice
after listening: 0.82-1.76 s of the source (the voice ends before a rumble
at ~2.2 s and a steady ~420 Hz "strings" tone that rises from ~1.7 s), at
32,000 Hz, which keeps everything the MP3 has (nothing above 16 kHz): 15 KB.

    python3 src/custom/fahhh/make_sample.py "path/to/Fahhhh.mp3"
    python3 src/custom/fahhh/make_sample.py in.mp3 --preview out.wav

Any --rate works: fahhh.c steps through the sample at FAH_RATE / 44100 frames
per output sample. The room is measured: the effect without its sample is
10,786 bytes of code+data against the 29,576 cap, so the ADPCM can take
~18.7 KB (test_fahhh.py keeps it under 18,000).

Needs numpy, scipy and soundfile (libsndfile >= 1.1 reads MP3).
"""
from __future__ import annotations

import argparse
from math import gcd
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent

# The reference pitch of the recording, for the Note mode. The "Fahhh" is a
# breathy, reverberant shout with no steady fundamental; a harmonic-sum search
# over 0.9-2.2 s keeps landing on 243 Hz (just under B3), with the 5th and 6th
# harmonics (1216, 1452-1474 Hz) carrying most of the energy. Playing a B3 in
# Note mode therefore plays the recording at its own speed.
REF_HZ = 243.0

STEP = [
    7, 8, 9, 10, 11, 12, 13, 14, 16, 17, 19, 21, 23, 25, 28, 31, 34, 37, 41, 45,
    50, 55, 60, 66, 73, 80, 88, 97, 107, 118, 130, 143, 157, 173, 190, 209, 230,
    253, 279, 307, 337, 371, 408, 449, 494, 544, 598, 658, 724, 796, 876, 963,
    1060, 1166, 1282, 1411, 1552, 1707, 1878, 2066, 2272, 2499, 2749, 3024, 3327,
    3660, 4026, 4428, 4871, 5358, 5894, 6484, 7132, 7845, 8630, 9493, 10442,
    11487, 12635, 13899, 15289, 16818, 18500, 20350, 22385, 24623, 27086, 29794,
    32767,
]
INDEX_ADJ = [-1, -1, -1, -1, 2, 4, 6, 8]


def ima_encode(pcm: np.ndarray) -> bytes:
    """Standard IMA ADPCM; predictor and index start at 0. Low nibble first."""
    pred, idx = 0, 0
    nibbles = []
    for s in pcm.astype(np.int32):
        step = STEP[idx]
        diff = int(s) - pred
        code = 0
        if diff < 0:
            code = 8
            diff = -diff
        delta = step >> 3
        if diff >= step:
            code |= 4
            diff -= step
            delta += step
        if diff >= step >> 1:
            code |= 2
            diff -= step >> 1
            delta += step >> 1
        if diff >= step >> 2:
            code |= 1
            delta += step >> 2
        pred = pred - delta if code & 8 else pred + delta
        pred = max(-32768, min(32767, pred))
        idx = max(0, min(88, idx + INDEX_ADJ[code & 7]))
        nibbles.append(code)
    if len(nibbles) % 2:
        nibbles.append(0)
    return bytes(nibbles[i] | (nibbles[i + 1] << 4) for i in range(0, len(nibbles), 2))


def ima_decode(data: bytes, n: int) -> np.ndarray:
    """The decoder fahhh.c runs, in Python, for the preview and the tests."""
    pred, idx = 0, 0
    out = np.zeros(n, np.int32)
    for i in range(n):
        code = (data[i >> 1] >> (4 * (i & 1))) & 15
        step = STEP[idx]
        delta = step >> 3
        if code & 4:
            delta += step
        if code & 2:
            delta += step >> 1
        if code & 1:
            delta += step >> 2
        pred = pred - delta if code & 8 else pred + delta
        pred = max(-32768, min(32767, pred))
        idx = max(0, min(88, idx + INDEX_ADJ[code & 7]))
        out[i] = pred
    return out


def prepare(path: Path, rate: int, start: float, end: float, fade_in: float, fade_out: float) -> np.ndarray:
    import soundfile as sf
    from scipy.signal import resample_poly

    x, sr = sf.read(str(path), always_2d=True, dtype="float64")
    mono = x.mean(axis=1)
    seg = mono[int(start * sr):int(end * sr)]
    g = gcd(rate, sr)
    y = resample_poly(seg, rate // g, sr // g)
    fi, fo = int(fade_in * rate), int(fade_out * rate)
    if fi:
        y[:fi] *= np.linspace(0.0, 1.0, fi)
    if fo:
        y[-fo:] *= np.linspace(1.0, 0.0, fo) ** 2
    return y / np.max(np.abs(y)) * 0.97


def write_header(out: Path, data: bytes, n: int, rate: int, source: str, start: float, end: float) -> None:
    rows = [", ".join(f"0x{b:02X}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    out.write_text(
        "/* Generated by make_sample.py. Do not edit by hand.\n"
        f" * Source: {source}, {start:.3f}-{end:.3f} s, mono,\n"
        f" * {rate} Hz, 4-bit IMA ADPCM (predictor and index start at 0, low nibble first). */\n"
        "#ifndef FAHHH_SAMPLE_H\n#define FAHHH_SAMPLE_H\n\n"
        f"#define FAH_SAMPLES {n}\n"
        f"#define FAH_RATE {rate}.0f\n"
        f"#define FAH_REF_HZ {REF_HZ:.1f}f\n"
        f"#define FAH_REF_INV {1.0 / REF_HZ:.9e}f   /* 1 / FAH_REF_HZ */\n"
        f"#define FAH_RATE_BASE {rate / 44100.0:.9e}f   /* FAH_RATE / 44100: frames per output sample */\n"
        f"#define FAH_ADPCM_BYTES {len(data)}\n\n"
        f"static const unsigned char FAH_ADPCM[{len(data)}] = {{\n"
        + ",\n".join("    " + r for r in rows)
        + "\n};\n\n#endif /* FAHHH_SAMPLE_H */\n"
    )


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("source", type=Path, help="the recording (MP3, WAV, ...)")
    ap.add_argument("--rate", type=int, default=32000, help="stored sample rate (default 32000)")
    ap.add_argument("--start", type=float, default=0.82,
                    help="seconds into the source; the 'F' starts rising at ~0.8 s (default 0.82)")
    ap.add_argument("--end", type=float, default=1.76,
                    help="seconds; the voice ends before the ~420 Hz tone rises and the rumble at ~2.2 s (default 1.76)")
    ap.add_argument("--fade-in", type=float, default=0.005)
    ap.add_argument("--fade-out", type=float, default=0.20)
    ap.add_argument("--out", type=Path, default=HERE / "fahhh_sample.h")
    ap.add_argument("--preview", type=Path, help="also write the decoded sample, at 44.1 kHz, to this WAV")
    a = ap.parse_args()

    y = prepare(a.source, a.rate, a.start, a.end, a.fade_in, a.fade_out)
    pcm = np.round(y * 32767).astype(np.int32)
    data = ima_encode(pcm)
    dec = ima_decode(data, len(pcm))
    err = dec - pcm
    snr = 10 * np.log10(np.sum(pcm.astype(float) ** 2) / max(1.0, float(np.sum(err.astype(float) ** 2))))
    write_header(a.out, data, len(pcm), a.rate, a.source.name, a.start, a.end)
    print(f"{a.out}: {len(pcm)} samples, {len(pcm) / a.rate:.2f} s at {a.rate} Hz, "
          f"{len(data)} bytes ADPCM, SNR {snr:.1f} dB")
    if a.preview:
        import soundfile as sf
        from scipy.signal import resample_poly
        g = gcd(44100, a.rate)
        sf.write(str(a.preview), resample_poly(dec / 32768.0, 44100 // g, a.rate // g), 44100, subtype="PCM_16")
        print(f"{a.preview}: decoded preview")


if __name__ == "__main__":
    main()
